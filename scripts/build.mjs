import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync, mkdtempSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import vm from 'node:vm';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = (path) => readFileSync(join(root, path), 'utf8');
const pkg = JSON.parse(read('package.json'));
const config = JSON.parse(read('config/sites.json'));
const runtimeSource = read('src/runtime.js');
const css = read('src/light-theme.css');
const sandbox = { URL };
vm.runInNewContext(runtimeSource, sandbox);
const runtime = sandbox.SubstackLightReader;

if (!/^\d+\.\d+\.\d+$/.test(pkg.version) || !/^\d+\.\d+\.\d+$/.test(pkg.lightReader.userscriptVersion)) {
  throw new Error('Chrome and userscript versions must contain three numeric parts.');
}
const customHosts = config.customSites.map((site) => site.hostname);
if (customHosts.some((host) => !/^[a-z0-9.-]+$/.test(host)) || new Set(customHosts).size !== customHosts.length) {
  throw new Error('Invalid or duplicate custom hostname.');
}
const matches = [config.standardPattern, ...customHosts.map((host) => `https://${host}/*`)];
const excluded = [
  'https://substack.com/*',
  ...runtime.RESERVED_SUBDOMAINS.map((host) => `https://${host}.substack.com/*`),
  ...runtime.BLOCKED_PATH_PREFIXES.flatMap((path) => [
    `https://*/${path}`,
    `https://*/${path}?*`,
    `https://*/${path}/*`
  ]),
  'https://*/p/*/edit', 'https://*/p/*/edit?*', 'https://*/p/*/edit/*',
  'https://*/p/*/preview', 'https://*/p/*/preview?*', 'https://*/p/*/preview/*'
];
// Explicitly generated files only; unrelated files are never packaged.
const generated = new Map();
const emit = (path, content) => generated.set(path, Buffer.isBuffer(content) ? content : Buffer.from(content));
const manifest = JSON.parse(read('src/extension/manifest.json'));
manifest.version = pkg.version;
manifest.host_permissions = matches;
manifest.content_scripts[0].matches = matches;
manifest.content_scripts[0].exclude_matches = excluded;
emit('extension/manifest.json', JSON.stringify(manifest, null, 2) + '\n');
emit('extension/runtime.js', runtimeSource);
emit('extension/light-theme.css', css);
for (const name of readdirSync(join(root, 'src/extension'))) {
  if (name !== 'manifest.json') emit(`extension/${name}`, read(`src/extension/${name}`));
}
emit('extension/sites.js', `// Generated from config/sites.json.\n(() => {\n  const hosts = new Set(${JSON.stringify(customHosts, null, 2)});\n  globalThis.SubstackLightReaderSites = Object.freeze({\n    isSupportedURL(value) {\n      try {\n        const url = new URL(value);\n        return url.protocol === 'https:' && (url.hostname.endsWith('.substack.com') || hosts.has(url.hostname));\n      } catch { return false; }\n    }\n  });\n})();\n`);
for (const size of [16, 32, 48, 128]) {
  emit(`extension/icons/${size}.png`, readFileSync(join(root, `assets/icons/${size}.png`)));
}
for (const name of ['LICENSE', 'PRIVACY.md']) emit(`extension/${name}`, read(name));

const metadata = [
  '// ==UserScript==',
  '// @name         Art & Biz Substack 亮色阅读模式',
  '// @namespace    local.artandbiz.light',
  `// @version      ${pkg.lightReader.userscriptVersion}`,
  '// @description  Substack Light Reader: local-only light themes for dark publication reading pages.',
  '// @license      MIT',
  ...matches.map((pattern) => `// @match        ${pattern}`),
  '// @run-at       document-start',
  '// @noframes',
  '// @grant        none',
  '// ==/UserScript=='
].join('\n');
const script = `${metadata}\n\n// Generated by npm run build. Edit src/ and config/, then rebuild.\n(() => {\n  'use strict';\n  const scope = {};\n  (function (globalThis) {\n${runtimeSource}\n  })(scope);\n  const runtime = scope.SubstackLightReader;\n  const themeCSS = ${JSON.stringify(css)};\n${read('src/userscript/entry.js')}\n})();\n`;
emit('userscript/substack-light-reader.user.js', script);

if (process.argv.includes('--check')) {
  const stale = [...generated].filter(([path, expected]) => {
    try { return !readFileSync(join(root, path)).equals(expected); } catch { return true; }
  }).map(([path]) => path);
  if (stale.length) throw new Error(`Generated files are stale. Run npm run build:\n${stale.join('\n')}`);
  console.log('Generated extension, userscript, domain lists and CSS are in sync.');
} else {
  for (const [path, bytes] of generated) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), bytes);
  }
  const dist = join(root, 'dist');
  mkdirSync(dist, { recursive: true });
  const zipName = `substack-light-reader-v${pkg.version}.zip`;
  const scriptName = `substack-light-reader-v${pkg.lightReader.userscriptVersion}.user.js`;
  const staging = mkdtempSync(join(tmpdir(), 'substack-light-reader-build-'));
  try {
    const entries = [...generated.keys()].filter((name) => name.startsWith('extension/')).map((name) => name.slice('extension/'.length)).sort();
    try {
      execFileSync('zip', ['-X', '-q', join(staging, zipName), ...entries], { cwd: join(root, 'extension'), stdio: 'pipe' });
    } catch (error) {
      throw new Error(`Cannot package extension. Install the standard zip command (or use WSL on Windows). ${error.message}`);
    }
    // A newly created ZIP avoids retaining removed files from older versions.
    copyFileSync(join(staging, zipName), join(dist, zipName));
    writeFileSync(join(dist, scriptName), script);
    const sums = [zipName, scriptName].map((name) => `${createHash('sha256').update(readFileSync(join(dist, name))).digest('hex')}  ${name}`).join('\n') + '\n';
    writeFileSync(join(dist, 'SHA256SUMS.txt'), sums);
    console.log(`Built extension ${pkg.version} and userscript ${pkg.lightReader.userscriptVersion}. Release files are in dist/.`);
  } finally {
    // Only the exact temporary directory created above is removed.
    rmSync(staging, { recursive: true, force: true });
  }
}
